/**
 * A test fixture, not data: the names of the Enochian tablets as the sources
 * print them, gathered in plan 090's stage 0 (19 November 2026) so that the
 * tests can hold `tabletNames` to them (`tabletNames.test.ts`). It is not
 * published: nothing the package exports imports it, `build.ts` compiles
 * only `.json5`, `tsconfig.build.json` emits only the exported modules and
 * `files` in package.json leaves `src/` out of the tarball, which the smoke
 * test checks. So it has no row in the README's Sources table.
 *
 * Names are facts (plan 091, "What follows for the site"): each entry is a
 * name a source prints, with where (`source`, a work of
 * `magick-data/enochian/tabletNotes`, its archive.org `item`, `page` as
 * printed and `leaf`, the scan's `/page/n{leaf}`); nothing else of the
 * sources' text is copied. `kind` and `quarter` say where the source
 * places the name, by `tabletNames`' kinds and quarters (the Union's and
 * the archangels' among them since plan 090's stage 4), with the kinds it
 * has not got (a quarter's other columns, and names built with Dee's
 * Black Cross); `note` is ours. `status` says what the name is:
 *
 * - `path`: read along a path in some version's letters (the tests check
 *   which);
 * - `pronunciation`: a name with vowels sounded, or a source's example of
 *   how to say one;
 * - `notAName`: not a name of the tablets' paths (a demon's root, a whole
 *   line, a name of the Earth);
 * - `doubledSquare`, `secondLetters`, `spelling`, `prefix`: the cited
 *   spellings no path gives, as `tabletNotes`' `citedSpellings` gives
 *   their reasons;
 * - `misprint`: a slip of the print beside the right reading;
 * - `blackCross`: built with, or part of, Dee's Black Cross;
 * - `backward`: a name read backward, for the wicked;
 * - `earlyGuess`: Dee's reading of the King before the answer of p.189.
 *
 * `GD_CITED_NAMES` are the Golden Dawn's: Regardie 1940 (vol. 4) and 1939
 * (vol. 3), the Equinox I.7 and I.8. `DEE_CITED_NAMES` are Dee's record,
 * Casaubon 1659, where every name of a table is ORO's (the data's Air, of
 * the East) but Vastrim, MOR's.
 */
import type { TabletQuarter } from "../TabletNames.ts";
import type { TabletWorkId } from "../TabletNotes.ts";
import type { EnochianWatchtowerID } from "../Tablets.ts";

/** What a cited name is (the header). */
export type CitedNameStatus =
  | "path"
  | "pronunciation"
  | "notAName"
  | "doubledSquare"
  | "secondLetters"
  | "spelling"
  | "prefix"
  | "misprint"
  | "blackCross"
  | "backward"
  | "earlyGuess";

/** Where a source places a name: `tabletNames`' kinds and others. */
export type CitedNameKind =
  | "holyName"
  | "king"
  | "senior"
  | "crossColumn"
  | "crossRow"
  | "topRow"
  | "servient"
  /** A column of a quarter outside its cross, read down. */
  | "column"
  | "union"
  | "unionColumn"
  | "kerubicArchangel"
  | "servientArchangel"
  | "demonRoot"
  | "middleLine"
  | "blackCrossName"
  | "blackCrossLine"
  | "blackCrossTransversary"
  | "demon"
  | "earthName";

/** One name a source prints. */
export interface CitedName {
  source: TabletWorkId;
  item: string;
  /** The file within the item, where it holds several. */
  file?: string;
  /** As printed: a page or a range. */
  page: string;
  leaf: number;
  /** Dee's name of the table. */
  table?: "ORO" | "MOR";
  tablet?: EnochianWatchtowerID | "union";
  kind?: CitedNameKind;
  quarter?: TabletQuarter;
  /** A Senior Dee first gives at six letters, without its first square. */
  reading?: "sixLetters";
  name: string;
  status: CitedNameStatus;
  note?: string;
}

