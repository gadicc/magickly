import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

/**
 * Writes the reading's grammar notes (plan 081, S1) into a module, so the
 * reading's route carries them in its bundle rather than reading
 * `grammar.md` from disk at run time. `grammar.test.ts` beside the module
 * fails when the two differ; run `pnpm reading:grammar` after editing the
 * notes, and commit the module with them.
 */

const here = (path: string) => fileURLToPath(new URL(path, import.meta.url));

/** The notes, in the data package. */
export const GRAMMAR_SOURCE = here(
  "../../packages/magick-data/src/enochian/grammar.md",
);

/** The module the reading imports. */
export const GRAMMAR_MODULE = here(
  "../../src/app/enochian/translate/reading/grammar.generated.ts",
);

/** The module's text for the notes as given. */
export function grammarModule(markdown: string): string {
  return [
    "// Generated by `pnpm reading:grammar` from",
    "// packages/magick-data/src/enochian/grammar.md: do not edit.",
    "",
    "/** `grammar.md`, whole: the reading's grammar notes (plan 081, S1). */",
    "export const GRAMMAR =",
    `  ${JSON.stringify(markdown)};`,
    "",
  ].join("\n");
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  writeFileSync(
    GRAMMAR_MODULE,
    grammarModule(readFileSync(GRAMMAR_SOURCE, "utf8")),
  );
  console.log(`Wrote ${GRAMMAR_MODULE}`);
}
